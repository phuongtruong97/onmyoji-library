-- Sua cac du an da cai ham quan tri nhung chua co bang nhat ky thao tac.
create table if not exists public.admin_moderation_log (
  id bigint generated by default as identity primary key,
  admin_user_id uuid not null references auth.users(id) on delete restrict,
  target_kind text not null,
  target_id bigint not null,
  action text not null,
  created_at timestamptz not null default now()
);

create index if not exists admin_moderation_log_created_at_idx
  on public.admin_moderation_log (created_at desc);

create index if not exists admin_moderation_log_target_idx
  on public.admin_moderation_log (target_kind, target_id);

alter table public.admin_moderation_log enable row level security;
revoke all on table public.admin_moderation_log from anon, authenticated;

comment on table public.admin_moderation_log is
  'Nhat ky noi bo cho cac thao tac duyet, tu choi, an va xoa tren trang admin.';
